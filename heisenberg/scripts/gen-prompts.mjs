#!/usr/bin/env node
// Bundle prompts/**/*.prompt into lib/prompts.generated.ts.
//
// Route handlers import prompt text from that module instead of reading files
// at request time, so nothing depends on Vercel's file tracing
// (outputFileTracingIncludes) and prompts are guaranteed to ship with the build.
//
//   node scripts/gen-prompts.mjs           rewrite lib/prompts.generated.ts
//   node scripts/gen-prompts.mjs --check   exit 1 if it is out of date
//
// Runs automatically before `dev` and `build` (see package.json).

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const promptsDir = join(root, "prompts")
const outFile = join(root, "lib", "prompts.generated.ts")

const sources = {}
for (const group of readdirSync(promptsDir, { withFileTypes: true })) {
  // Directories starting with "_" (e.g. _parity) hold test fixtures, not prompts.
  if (!group.isDirectory() || group.name.startsWith("_")) continue
  for (const file of readdirSync(join(promptsDir, group.name)).sort()) {
    if (!file.endsWith(".prompt")) continue
    const id = `${group.name}/${file.slice(0, -".prompt".length)}`
    sources[id] = readFileSync(join(promptsDir, group.name, file), "utf8")
  }
}

const body = Object.keys(sources)
  .sort()
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(sources[id])},`)
  .join("\n")
const output =
  `// GENERATED by scripts/gen-prompts.mjs from prompts/**/*.prompt -- do not edit.\n` +
  `// Edit the .prompt files, then run \`pnpm gen:prompts\`.\n\n` +
  `export const PROMPT_SOURCES: Record<string, string> = {\n${body}\n}\n`

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : ""
  if (current !== output) {
    console.error(`${relative(root, outFile)} is out of date: run \`pnpm gen:prompts\``)
    process.exit(1)
  }
  console.log(`${relative(root, outFile)} is up to date`)
} else {
  writeFileSync(outFile, output)
  console.log(`wrote ${Object.keys(sources).length} prompts to ${relative(root, outFile)}`)
}
